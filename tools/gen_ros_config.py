#!/usr/bin/env python3
"""gen_ros_config.py — firmware/src/config.h → ros2/ras_arm_description/config/arm.yaml.

The ROS 2 twin (URDF, Gazebo workcell, controllers) reads its geometry, joint limits, speed limits
and workcell from this generated file, so config.h stays the single source of truth
(CI fails when the YAML is out of date). SI units in the YAML: m, rad, rad/s.
Run from the repo root:  python3 tools/gen_ros_config.py
"""
import math, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "firmware/src/config.h")
OUT = os.path.join(ROOT, "ros2/ras_arm_description/config/arm.yaml")
JOINTS = ["J1", "J2", "J3", "J4", "J5", "J6"]


def parse(text):
    defs = {m[1]: float(m[2]) for m in re.finditer(r"^#define\s+(\w+)\s+(-?\d+(?:\.\d+)?)f?\b", text, re.M)}
    arrays = {m[1]: [float(v.strip().rstrip("f")) for v in m[2].split(",")]
              for m in re.finditer(r"static const float (\w+)\[NJ\]\s*=\s*\{([^}]*)\}", text)}
    return defs, arrays


def ik(d, x, y, z, roll):
    """same IK as kinematics.c (docs/kinematics.md), degrees in and out"""
    r, zw = math.hypot(x, y), z + d["L3"] - d["H_SHOULDER"]
    j3 = math.acos((r * r + zw * zw - d["L1"] ** 2 - d["L2"] ** 2) / (2 * d["L1"] * d["L2"]))
    j2 = math.atan2(r, zw) - math.atan2(d["L2"] * math.sin(j3), d["L1"] + d["L2"] * math.cos(j3))
    j1, j2, j3 = math.degrees(math.atan2(y, x)), math.degrees(j2), math.degrees(j3)
    return [j1, j2, j3, 0.0, 180.0 - j2 - j3, roll - j1]


def main():
    with open(SRC) as f:
        d, a = parse(f.read())
    m = lambda v: round(v / 1000.0, 6)
    rad = lambda v: round(math.radians(v), 9)       # 9 places: ±90° stays ±π/2, the IK's exact value at the bins
    home = ik(d, d["CELL_HOME_X"], 0.0, d["CELL_HOME_Z"], 0.0)
    L = ["# GENERATED by tools/gen_ros_config.py from firmware/src/config.h — do not edit.",
         "# SI units (m, rad, rad/s); the firmware works in mm and degrees.",
         "geometry:          # L1, L2, L3, H_SHOULDER",
         f"  l1: {m(d['L1'])}", f"  l2: {m(d['L2'])}", f"  l3: {m(d['L3'])}", f"  h_shoulder: {m(d['H_SHOULDER'])}",
         "joints:            # JOINT_MIN / JOINT_MAX / JOINT_MAX_DPS"]
    for j, name in enumerate(JOINTS):
        L.append(f"  {name}: {{lower: {rad(a['JOINT_MIN'][j])}, upper: {rad(a['JOINT_MAX'][j])}, velocity: {rad(a['JOINT_MAX_DPS'][j])}}}")
    L += ["gripper:           # per finger, from the centre line = opening / 2 (grip value in mm)",
          f"  lower: {m(a['JOINT_MIN'][6] / 2)}", f"  upper: {m(a['JOINT_MAX'][6] / 2)}",
          f"  velocity: {m(a['JOINT_MAX_DPS'][6] / 2)}",
          f"  open: {m(d['GRIP_OPEN_MM'] / 2)}", f"  closed: {m(d['GRIP_CLOSED_MM'] / 2)}",
          "cell:              # robot frame: x → cradle, y left, z up, origin = base axis on the table",
          f"  home: [{m(d['CELL_HOME_X'])}, 0.0, {m(d['CELL_HOME_Z'])}]",
          f"  home_joints: [{', '.join(str(rad(v)) for v in home)}]   # IK of home",
          f"  cradle_x: {m(d['CELL_CRADLE_X'])}", f"  grip_z: {m(d['CELL_GRIP_Z'])}",
          f"  bin_y: {m(d['CELL_BIN_Y'])}", f"  drop_z: {m(d['CELL_DROP_Z'])}",
          f"  safe_z: {m(d['SAFE_Z'])}", f"  place_above_dz: {m(d['PLACE_ABOVE_DZ'])}",
          "motion:            # the RUN cycle's timing: minimum move times (s), straight-line speeds (m/s)",
          f"  ramp: {d['RAMP_FRACTION']}",
          f"  move_s: {{home: {d['MOVE_HOME_MS'] / 1000}, transit: {d['MOVE_TRANSIT_MS'] / 1000}, "
          f"above: {d['MOVE_ABOVE_MS'] / 1000}, grip: {d['GRIP_MOVE_MS'] / 1000}}}",
          f"  line_m_s: {{pick_down: {m(d['PICK_DOWN_MM_S'])}, pick_up: {m(d['PICK_UP_MM_S'])}, "
          f"place_down: {m(d['PLACE_DOWN_MM_S'])}, place_up: {m(d['PLACE_UP_MM_S'])}}}",
          f"  line_step: {m(d['LINE_STEP_MM'])}"]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"→ {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
