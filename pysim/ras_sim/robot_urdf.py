"""The arm's URDF, generated from config.h (geometry, joint limits) and SIM (masses, torques).

Same chain, names, signs and zero pose as the ROS 2 twin (ros2/ras_arm_description/urdf/ras_arm.xacro on
feature/ros2-twin): a joint position is the firmware angle in rad, a finger is the opening / 2 in m.
Zero pose = everything straight up, facing +x (the cradle).

    J1 yaw (z) → turret → J2 pitch (y) at H → upper arm L1 → J3 pitch (y) → J4 roll (z) → forearm L2
       → J5 pitch (y) → J6 roll (−z) → tool L3 → tool_tip (the firmware's x, y, z, roll) + 2 fingers (±y)

The stepper joints get a hard stop SIM.hard_stop_margin past their range, so a homing switch (which
clicks at the end of the range) is reached before the mechanics stop the joint.
"""
from __future__ import annotations

import math
from pathlib import Path

from .config import FW, SIM

MATERIALS = {"orange": (0.89, 0.64, 0.23), "dark": (0.20, 0.23, 0.28), "grey": (0.54, 0.58, 0.64),
             "light": (0.79, 0.81, 0.84)}


def _f(v: float) -> str:
    return f"{v:.6g}"


def _xyz(*v) -> str:
    return " ".join(_f(c) for c in v)


def _box(size, xyz=(0, 0, 0)):
    return f'<origin xyz="{_xyz(*xyz)}"/><geometry><box size="{_xyz(*size)}"/></geometry>'


def _cyl(r, length, xyz=(0, 0, 0), along_y=False):
    rpy = f' rpy="{_f(math.pi / 2)} 0 0"' if along_y else ""
    return f'<origin xyz="{_xyz(*xyz)}"{rpy}/><geometry><cylinder radius="{_f(r)}" length="{_f(length)}"/></geometry>'


def _inertial(m, size, xyz):
    x, y, z = size
    return (f'<inertial><origin xyz="{_xyz(*xyz)}"/><mass value="{_f(m)}"/>'
            f'<inertia ixx="{_f(m * (y * y + z * z) / 12)}" iyy="{_f(m * (x * x + z * z) / 12)}" '
            f'izz="{_f(m * (x * x + y * y) / 12)}" ixy="0" ixz="0" iyz="0"/></inertial>')


def _link(name, visuals, collision, inertial):
    vis = "".join(f'<visual>{g}<material name="{mat}"/></visual>' for g, mat in visuals)
    col = f"<collision>{collision}</collision>" if collision else ""
    return f'<link name="{name}">{vis}{col}{inertial}</link>'


def _revolute(name, parent, child, xyz, axis, j):
    lo, hi = FW.JOINT_MIN[j], FW.JOINT_MAX[j]
    if j < FW.N_STEPPERS:
        lo, hi = lo - SIM.hard_stop_margin, hi + SIM.hard_stop_margin
    vel = math.radians(max(FW.JOINT_MAX_DPS[j], SIM.servo_dps if j >= FW.N_STEPPERS else 0) * 1.5)
    return (f'<joint name="{name}" type="revolute"><parent link="{parent}"/><child link="{child}"/>'
            f'<origin xyz="{_xyz(*xyz)}"/><axis xyz="{axis}"/>'
            f'<limit lower="{_f(math.radians(lo))}" upper="{_f(math.radians(hi))}" velocity="{_f(vel)}" '
            f'effort="{_f(SIM.effort[name])}"/><dynamics damping="0.02" friction="0"/></joint>')


def arm_urdf() -> str:
    mm = 0.001
    H, L1, L2, L3 = FW.H_SHOULDER * mm, FW.L1 * mm, FW.L2 * mm, FW.L3 * mm
    FINGER, BEYOND = SIM.finger_len * mm, SIM.finger_beyond * mm
    FZ = BEYOND - FINGER / 2                         # finger centre, from the tip
    TOOL = L3 - FINGER + BEYOND                      # tool body length (wrist → finger root)
    M = SIM.mass
    grip_hi = (FW.JOINT_MAX[FW.JG] / 2) * mm         # per finger

    parts = ['<?xml version="1.0"?>', "<!-- GENERATED by pysim/ras_sim/robot_urdf.py from firmware/src/config.h -->",
             '<robot name="ras_arm">']
    parts += [f'<material name="{k}"><color rgba="{_xyz(*v)} 1"/></material>' for k, v in MATERIALS.items()]

    parts.append(_link("base_link", [(_cyl(0.08, 0.008, (0, 0, 0.004)), "dark")], _cyl(0.08, 0.008, (0, 0, 0.004)),
                       _inertial(M["base_link"], (0.16, 0.16, 0.008), (0, 0, 0.004))))
    parts.append(_revolute("J1", "base_link", "turret", (0, 0, 0), "0 0 1", FW.J1))
    tz = (H + 0.008) / 2
    parts.append(_link("turret", [(_cyl(0.062, H - 0.008, (0, 0, tz)), "dark")], _cyl(0.062, H - 0.008, (0, 0, tz)),
                       _inertial(M["turret"], (0.124, 0.124, H), (0, 0, H / 2))))
    parts.append(_revolute("J2", "turret", "upper_arm", (0, 0, H), "0 1 0", FW.J2))
    parts.append(_link("upper_arm", [(_cyl(0.03, 0.044, along_y=True), "dark"), (_box((0.04, 0.04, L1), (0, 0, L1 / 2)), "orange")],
                       _box((0.04, 0.04, L1 - 0.03), (0, 0, L1 / 2 + 0.015)),
                       _inertial(M["upper_arm"], (0.04, 0.04, L1), (0, 0, L1 / 2))))
    parts.append(_revolute("J3", "upper_arm", "forearm", (0, 0, L1), "0 1 0", FW.J3))
    parts.append(_link("forearm", [(_cyl(0.022, 0.044, along_y=True), "dark")], None,
                       _inertial(M["forearm"], (0.044, 0.044, 0.044), (0, 0, 0))))
    parts.append(_revolute("J4", "forearm", "forearm_roll", (0, 0, 0), "0 0 1", FW.J4))
    parts.append(_link("forearm_roll", [(_box((0.032, 0.032, L2), (0, 0, L2 / 2)), "orange")],
                       _box((0.032, 0.032, L2 - 0.04), (0, 0, L2 / 2)),
                       _inertial(M["forearm_roll"], (0.032, 0.032, L2), (0, 0, L2 / 2))))
    parts.append(_revolute("J5", "forearm_roll", "wrist", (0, 0, L2), "0 1 0", FW.J5))
    parts.append(_link("wrist", [(_cyl(0.016, 0.044, along_y=True), "dark")], None,
                       _inertial(M["wrist"], (0.032, 0.044, 0.032), (0, 0, 0))))
    # J6 axis −z: with the gripper pointing down, + J6 turns the fingers + in world yaw (yaw = J1 + J6 = roll)
    parts.append(_revolute("J6", "wrist", "tool", (0, 0, 0), "0 0 -1", FW.J6))
    parts.append(_link("tool", [(_box((0.026, 0.026, TOOL), (0, 0, TOOL / 2)), "grey"),
                                (_box((0.02, 0.07, 0.008), (0, 0, TOOL)), "grey")],
                       _box((0.026, 0.026, TOOL - 0.03), (0, 0, TOOL / 2 + 0.015)),
                       _inertial(M["tool"], (0.026, 0.07, TOOL), (0, 0, TOOL / 2))))
    parts.append('<joint name="tool_tip_joint" type="fixed"><parent link="tool"/><child link="tool_tip"/>'
                 f'<origin xyz="0 0 {_f(L3)}"/></joint>')
    parts.append('<link name="tool_tip"><inertial><mass value="0.001"/>'
                 '<inertia ixx="1e-9" iyy="1e-9" izz="1e-9" ixy="0" ixz="0" iyz="0"/></inertial></link>')
    for side, sign in (("left", 1), ("right", -1)):
        geo = _box((0.014, 0.008, FINGER), (0, sign * 0.004, FZ))
        parts.append(_link(f"finger_{side}", [(geo, "light")], geo,
                           _inertial(M["finger"], (0.014, 0.008, FINGER), (0, sign * 0.004, FZ))))
        parts.append(f'<joint name="grip_{side}" type="prismatic"><parent link="tool"/><child link="finger_{side}"/>'
                     f'<origin xyz="0 0 {_f(L3)}"/><axis xyz="0 {sign} 0"/>'
                     f'<limit lower="0" upper="{_f(grip_hi)}" velocity="0.2" effort="{_f(SIM.finger_force)}"/>'
                     '<dynamics damping="0.5" friction="0"/></joint>')
    parts.append("</robot>")
    return "\n".join(parts) + "\n"


def write_arm_urdf(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(arm_urdf(), encoding="utf-8")
    return path
